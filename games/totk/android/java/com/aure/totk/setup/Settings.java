package com.aure.totk.setup;

import java.math.BigDecimal;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.Map;

/** The player options of the pre-game menu: values, presets, the rules that tie options together, and the settings.env
 * text the runtime reads at game start (runtime/frontend_android.c, before <game>/totk.env, so a developer's totk.env
 * still wins). Plain Java without Android types so the host tests can run it (tests/test_android_settings.py). */
final class Settings {
    static final String PERFORMANCE = "performance", PICTURE = "picture", SCREEN = "screen", CONTROLS = "controls";
    static final String CUSTOM = "custom";
    /** Preset ids in card order; CUSTOM is computed, never applied. */
    static final String[] PRESETS = {"light", "balanced", "smooth", "60fps"};

    /** One option: a choice between fixed values, or a 0..100 slider (values == null). */
    static final class Option {
        final String key, tab, fallback;
        final String[] values;
        Option(String key, String tab, String fallback, String... values) {
            this.key = key; this.tab = tab; this.fallback = fallback; this.values = values.length == 0 ? null : values;
        }
        boolean slider() { return values == null; }
        boolean valid(String value) {
            if (value == null) return false;
            if (values != null) return Arrays.asList(values).contains(value);
            try { int v = Integer.parseInt(value); return v >= 0 && v <= 100; } catch (NumberFormatException bad) { return false; }
        }
        int index(String value) { return values == null ? -1 : Arrays.asList(values).indexOf(value); }
    }

    static final String[] LANGUAGES = {"auto", "en-US", "ja", "de", "fr", "es", "it", "nl", "ru", "ko", "zh-Hans", "zh-Hant", "pt-BR"};
    /** Every option in menu order; the fallback is the shipping default (an absent settings.env behaves the same). */
    static final Option[] OPTIONS = {
        new Option("frame_rate", PERFORMANCE, "30", "30", "40", "60", "unlimited"),
        new Option("frame_gen", PERFORMANCE, "off", "off", "on"),
        new Option("render_res", PERFORMANCE, "game", "game", "1280x720", "1152x648", "960x540"),
        new Option("latency", PERFORMANCE, "balanced", "responsive", "balanced", "smoothest"),
        new Option("gpu_feed", PERFORMANCE, "off", "off", "on"),
        new Option("upscaler", PICTURE, "off", "off", "fsr", "sgsr"),
        new Option("sharpness_fsr", PICTURE, "20"),
        new Option("sharpness_sgsr", PICTURE, "50"),
        new Option("aa", PICTURE, "fxaa", "fxaa", "smaa", "off"),
        new Option("shadows", PICTURE, "high", "high", "medium", "low"),
        new Option("console_mode", SCREEN, "handheld", "handheld", "docked"),
        new Option("native_hud", SCREEN, "off", "off", "on"),
        new Option("overlay", SCREEN, "off", "off", "fps", "full"),
        new Option("overlay_pos", SCREEN, "tr", "tl", "tr", "bl", "br"),
        new Option("second_screen", SCREEN, "on", "off", "on"),
        new Option("buttons", CONTROLS, "nintendo", "nintendo", "xbox"),
        new Option("audio_latency", CONTROLS, "balanced", "low", "balanced", "safe"),
        new Option("rumble", CONTROLS, "100", "0", "25", "50", "75", "100"),
        new Option("motion", CONTROLS, "on", "on", "off"),
        new Option("game_language", CONTROLS, "auto", LANGUAGES),
    };

    private static final String[] PRESET_KEYS = {"frame_rate", "frame_gen", "render_res", "latency", "upscaler", "aa", "shadows"};
    /** Rows follow PRESETS, columns PRESET_KEYS; null = not part of that preset (Smooth: latency is set by frame generation).
     * Light is exactly the Retroid Pocket Duo's device-approved profile (540p scene, full shadows). */
    private static final String[][] PRESET_VALUES = {
        {"30", "off", "960x540", "balanced", "off", "fxaa", "high"},
        {"30", "off", "game", "balanced", "off", "fxaa", "high"},
        {"30", "on", "1152x648", null, "off", "fxaa", "high"},
        {"60", "off", "game", "balanced", "off", "fxaa", "high"},
    };
    /** The qualified locked frame-generation profile (android/APP.md). DM_DETCLOCK / TOTK_MFX are dead on Android. */
    private static final String[] FRAMEGEN_BLOCK = {
        "TOTK_FPS60=0", "TOTK_FRAMEGEN=locked", "TOTK_REALTIME=1", "TOTK_FRAME_LAG=0", "TOTK_FPS_AUTO=0", "DM_PRESENT_HZ=60",
        "DM_PRESENT_INTERVAL=game", "TOTK_PRESENT_SLOTS=1", "TOTK_VK_PRESENT=ahb", "TOTK_ACQUIRE_SLACK=0", "TOTK_ACQUIRE_CLOCK=0",
        "TOTK_PACE=0", "TOTK_ASYNC_REPLAY=0"};
    static final String HEADER = "# Generated by the TotK Native menu (Graphics, Controls & audio) on every change and at game start.\n"
            + "# Do not edit: the menu overwrites it. Developer overrides belong in <game>/totk.env, which is read after this file.\n";

    private final Map<String, String> values = new LinkedHashMap<>();
    private final boolean fps60Hysteresis;

    /** Stored values (any map: SharedPreferences.getAll()); unknown keys and invalid values fall back to the defaults. */
    Settings(Map<String, ?> stored, String soc) {
        // Internal 60 fps profile policy, using the same chip class as gpu_feed. Recomputed for old stores too:
        // no preference key or menu option to migrate, and an explicit totk.env value still wins.
        fps60Hysteresis = "Snapdragon 8 Elite class".equals(socClass(soc));
        for (Option option : OPTIONS) {
            Object value = stored == null ? null : stored.get(option.key);
            values.put(option.key, value instanceof String && option.valid((String) value) ? (String) value : option.fallback);
        }
        // A hand-edited store must not hold a combination the menu cannot produce.
        if ("on".equals(get("frame_gen"))) values.put("frame_rate", "30");
        // 1.0.0/1.0.1 had no gpu_feed key. Only a missing key adopts the chip default; explicit choices win.
        if (stored == null || !stored.containsKey("gpu_feed")) values.put("gpu_feed", gpuFeedDefault(soc));
    }
    /** The first launch: shipping defaults with the profile for this chip (profile(soc)). */
    static Settings firstRun(String soc) {
        Settings settings = new Settings(null, soc);
        settings.applyPreset(profile(soc));
        return settings;
    }

    static Option option(String key) {
        for (Option option : OPTIONS) if (option.key.equals(key)) return option;
        throw new IllegalArgumentException(key);
    }
    Map<String, String> values() { return values; }
    String get(String key) { return values.get(option(key).key); }
    int number(String key) { return Integer.parseInt(get(key)); }

    /** Set one option, then apply the rules that tie options together: rates above 30 turn frame generation off,
     * frame generation needs 30 fps. Invalid values are ignored. */
    void set(String key, String value) {
        Option option = option(key);
        if (!option.valid(value)) return;
        values.put(key, value);
        if (key.equals("frame_rate") && !value.equals("30")) values.put("frame_gen", "off");
        if (key.equals("frame_gen") && value.equals("on")) values.put("frame_rate", "30");
    }
    /** The neighbouring value of a choice (wrapping), or the slider moved by step and clamped. */
    void step(String key, int direction) {
        Option option = option(key);
        if (option.slider()) { set(key, String.valueOf(Math.max(0, Math.min(100, number(key) + direction * 5)))); return; }
        int n = option.values.length, i = option.index(get(key));
        set(key, option.values[((i + direction) % n + n) % n]);
    }
    /** Frame generation fixes latency; uncapped producers must not queue acquire slack. */
    boolean latencyLocked() { return "on".equals(get("frame_gen")) || "40".equals(get("frame_rate")) || "unlimited".equals(get("frame_rate")); }
    /** Which sharpness slider the current upscaler uses, or null when there is no upscaler. */
    String sharpnessKey() {
        switch (get("upscaler")) {
            case "fsr": return "sharpness_fsr";
            case "sgsr": return "sharpness_sgsr";
            default: return null;
        }
    }

    /** The preset whose values all match, else CUSTOM. */
    String preset() {
        for (int p = 0; p < PRESETS.length; p++) if (matches(p)) return PRESETS[p];
        return CUSTOM;
    }
    private boolean matches(int preset) {
        for (int k = 0; k < PRESET_KEYS.length; k++) {
            String want = PRESET_VALUES[preset][k];
            if (want != null && !want.equals(values.get(PRESET_KEYS[k]))) return false;
        }
        return true;
    }
    /** Apply a preset's Performance and Picture values; Screen, Controls and the sharpness sliders are never touched. */
    void applyPreset(String name) {
        int preset = Arrays.asList(PRESETS).indexOf(name);
        if (preset < 0) return;
        for (int k = 0; k < PRESET_KEYS.length; k++) if (PRESET_VALUES[preset][k] != null) values.put(PRESET_KEYS[k], PRESET_VALUES[preset][k]);
    }
    /** One preset value (for the card captions), or null when the preset leaves it alone. */
    static String presetValue(String preset, String key) {
        int p = Arrays.asList(PRESETS).indexOf(preset), k = Arrays.asList(PRESET_KEYS).indexOf(key);
        return p < 0 || k < 0 ? null : PRESET_VALUES[p][k];
    }
    /** Build.SOC_MODEL as one whole token: trimmed, upper case, cut at the first '-' or space ("" when unknown). */
    static String socToken(String soc) {
        String s = soc == null ? "" : soc.trim().toUpperCase(java.util.Locale.ROOT);
        int cut = s.indexOf('-');
        if (cut >= 0) s = s.substring(0, cut);
        cut = s.indexOf(' ');
        return cut >= 0 ? s.substring(0, cut) : s;
    }
    /** The chip family a tested profile belongs to (each Dragonwing part with its Snapdragon counterpart), else null.
     * Exact tokens only, never board.platform or SOC_MANUFACTURER (the Duo reports platform "sun", manufacturer
     * "Moorechip"), and never a substring (a future part number may contain the same digits). */
    static String socClass(String soc) {
        switch (socToken(soc)) {
            case "CQ8725S": case "SM8750": return "Snapdragon 8 Elite class";                 // Adreno 830 (AYN Odin 3)
            case "QCS8550": case "QCM8550": case "SM8550": return "Snapdragon 8 Gen 2 class";  // Adreno 740 (AYN Thor)
            case "CQ7790S": case "CQ7790M": case "SM7750": return "Snapdragon 7 Gen 4 class";  // Adreno 722 (Retroid Pocket Duo)
            default: return null;
        }
    }
    /** The default preset for this chip from Build.SOC_MODEL only: the device-tested settings of its family, else Light,
     * the most conservative preset. The runtime never switches behaviour by device; experimental features (frame
     * generation) are off in every profile. */
    static String profile(String soc) {
        switch (socToken(soc)) {
            case "CQ8725S": case "SM8750": return "60fps";
            case "QCS8550": case "QCM8550": case "SM8550": return "balanced";
            default: return "light";   // the Eliza family (CQ7790S/M, SM7750) and every untested chip
        }
    }
    /** Restart-based Odin 3 pairs: Hateno 46.5 -> 57.3 fps, Lookout 52.2 -> 57.1 (4/4 pairs).
     * Duo at 60 fps worsened p95 by 4-5 ms; Thor was neutral. Keep this independent of the selected preset. */
    static String gpuFeedDefault(String soc) {
        return "Snapdragon 8 Elite class".equals(socClass(soc)) ? "on" : "off";
    }
    /** Whether profile(soc) is backed by a device test (the "Recommended for this device" badge). */
    static boolean profileKnown(String soc) { return socClass(soc) != null; }
    /** Y on a tab: the device's default values for that tab (the profile's preset for Performance and Picture). */
    void defaults(String tab, String soc) {
        for (Option option : OPTIONS) if (option.tab.equals(tab)) values.put(option.key, option.fallback);
        if (tab.equals(PERFORMANCE) || tab.equals(PICTURE)) {
            int p = Arrays.asList(PRESETS).indexOf(profile(soc));
            for (int k = 0; k < PRESET_KEYS.length; k++)
                if (PRESET_VALUES[p][k] != null && option(PRESET_KEYS[k]).tab.equals(tab)) values.put(PRESET_KEYS[k], PRESET_VALUES[p][k]);
        }
        if ("on".equals(get("frame_gen"))) values.put("frame_rate", "30");
        if (tab.equals(PERFORMANCE)) values.put("gpu_feed", gpuFeedDefault(soc));
    }

    /** settings.env: NAME=value lines in the totk.env format. locale = the device's first language as a BCP 47 tag
     * (LocaleList.getDefault().get(0).toLanguageTag()), used when the game language follows the device. dataDir = the
     * game folder when it is not the primary one (SD card), else null; written first, because the runtime reads it
     * before it chooses its data folder and log. */
    String env(String locale) { return env(locale, null); }
    String env(String locale, String dataDir) {
        StringBuilder out = new StringBuilder(HEADER);
        if (dataDir != null && dataDir.startsWith("/") && dataDir.indexOf('\n') < 0 && dataDir.indexOf('\r') < 0 && dataDir.indexOf('\0') < 0)
            line(out, "TOTK_DATA_DIR=" + dataDir);
        boolean framegen = "on".equals(get("frame_gen"));
        boolean forty = "40".equals(get("frame_rate"));
        boolean unlimited = "unlimited".equals(get("frame_rate"));
        if (framegen) for (String line : FRAMEGEN_BLOCK) line(out, line);
        else {
            boolean sixty = "60".equals(get("frame_rate"));
            line(out, "TOTK_FPS60=" + (sixty || forty || unlimited ? "1" : "0"));
            if (forty) {
                // Keep a 25 ms producer clock even when Android limits the display to 60 Hz.
                for (String setting : new String[]{"TOTK_UNCAPPED=1", "TOTK_UNCAPPED_HZ=40", "TOTK_UNCAPPED_INTERVAL=1",
                        "TOTK_REALTIME=1", "TOTK_FRAME_LAG=0", "TOTK_FPS_AUTO=0", "TOTK_PACE=0", "TOTK_PRESENT_SLOTS=auto",
                        "TOTK_ACQUIRE_SLACK=0", "TOTK_ACQUIRE_CLOCK=0", "TOTK_FRAME_RATE_HINT=1", "TOTK_FRAME_RATE_HINT_HZ=120"})
                    line(out, setting);
            }
            if (unlimited) {
                // The existing 120 Hz producer ceiling protects the realtime game clock.
                for (String setting : new String[]{"TOTK_UNCAPPED=1", "TOTK_UNCAPPED_HZ=120", "TOTK_UNCAPPED_INTERVAL=1",
                        "TOTK_REALTIME=1", "TOTK_FRAME_LAG=0", "TOTK_FPS_AUTO=0", "TOTK_PACE=0", "TOTK_PRESENT_SLOTS=0",
                        "TOTK_ACQUIRE_SLACK=0", "TOTK_ACQUIRE_CLOCK=0", "TOTK_FRAME_RATE_HINT=1", "TOTK_FRAME_RATE_HINT_HZ=max"})
                    line(out, setting);
            }
            // The device-tested 60 fps profile reports hardware GPU time (the FPS60 default, latency, overstates it).
            if (sixty) line(out, "TOTK_GPU_TIME=hardware");
            if (sixty && fps60Hysteresis) {
                line(out, "TOTK_FPS60_HYSTERESIS=1");
                line(out, "TOTK_FRAME_LAG=1");
            }
            // Extraction cannot split passes. Leave both hints out with frame generation, retaining its timing block.
            if ("on".equals(get("gpu_feed"))) {
                line(out, "TOTK_VK_SPLIT_PASS_DRAWS=512");
                line(out, "TOTK_ADPF_GPU=1");
            }
        }
        if (!get("render_res").equals("game")) line(out, "TOTK_RENDER_RES=" + get("render_res"));
        if (!framegen && !forty && !unlimited) line(out, "TOTK_ACQUIRE_SLACK=" + Arrays.asList("responsive", "balanced", "smoothest").indexOf(get("latency")));
        String upscaler = get("upscaler");
        line(out, "TOTK_POST_SCALE=" + upscaler);
        if (upscaler.equals("fsr")) line(out, "TOTK_POST_SHARPNESS=" + decimal(number("sharpness_fsr"), 2));
        if (upscaler.equals("sgsr")) line(out, "TOTK_POST_SGSR_SHARPNESS=" + decimal(number("sharpness_sgsr") * 4, 2));
        switch (get("aa")) {
            case "smaa": line(out, "TOTK_FXAA=0"); line(out, "TOTK_POST_AA=smaa"); break;
            case "off": line(out, "TOTK_FXAA=0"); break;
            default: break;
        }
        switch (get("shadows")) {
            case "medium": line(out, "TOTK_SHADOW_RES=288"); break;
            case "low": line(out, "TOTK_SHADOW_RES=256"); break;
            default: break;
        }
        line(out, "TOTK_OPERATION_MODE=" + get("console_mode"));
        line(out, "TOTK_NATIVE_UI=" + (get("native_hud").equals("on") ? "1" : "0"));
        line(out, "TOTK_OVERLAY=" + get("overlay"));
        line(out, "TOTK_OVERLAY_POS=" + get("overlay_pos"));
        line(out, "TOTK_COMPANION=" + (get("second_screen").equals("on") ? "1" : "0"));
        line(out, "TOTK_FACE_BUTTONS=" + (get("buttons").equals("xbox") ? "position" : "label"));
        line(out, "TOTK_AUDIO_PREFILL_MS=" + (get("audio_latency").equals("low") ? "10" : get("audio_latency").equals("safe") ? "40" : "20"));
        // Rumble strength 0 gives the game no vibration devices; otherwise the game's rumble times the strength.
        int rumble = number("rumble");
        line(out, "TOTK_RUMBLE=" + (rumble > 0 ? "1" : "0"));
        if (rumble > 0) line(out, "TOTK_RUMBLE_GAIN=" + decimal(rumble, 2));
        line(out, "TOTK_GYRO=" + (get("motion").equals("on") ? "1" : "0"));
        String language = get("game_language");
        if (!language.equals("auto")) line(out, "TOTK_LANG=" + language);
        else if (locale != null && locale.matches("[A-Za-z0-9-]{1,35}")) line(out, "TOTK_LOCALE=" + locale);   // never a malformed line
        return out.toString();
    }
    private static void line(StringBuilder out, String line) { out.append(line).append('\n'); }
    /** value / 10^scale as a plain decimal with at least one fraction digit (20 -> 0.2, 200 -> 2.0). */
    private static String decimal(int value, int scale) {
        BigDecimal d = BigDecimal.valueOf(value).movePointLeft(scale).stripTrailingZeros();
        return (d.scale() < 1 ? d.setScale(1) : d).toPlainString();
    }

    /** Write <dir>/<name> atomically: <name>.tmp, fsync, rename over the old file. On any failure the temp file is
     * removed, the previous file is left as it was, and the exception says why (shown to the player before starting). */
    static void writeAtomic(java.io.File dir, String name, String text) throws java.io.IOException {
        java.io.File target = new java.io.File(dir, name), temp = new java.io.File(dir, name + ".tmp");
        try (java.io.FileOutputStream out = new java.io.FileOutputStream(temp)) {
            out.write(text.getBytes(java.nio.charset.StandardCharsets.UTF_8));
            out.getFD().sync();
        } catch (java.io.IOException failed) {
            temp.delete();
            throw failed;
        }
        try {
            java.nio.file.Files.move(temp.toPath(), target.toPath(), java.nio.file.StandardCopyOption.REPLACE_EXISTING,
                    java.nio.file.StandardCopyOption.ATOMIC_MOVE);
        } catch (java.io.IOException failed) {
            temp.delete();
            throw failed;
        }
    }
}
