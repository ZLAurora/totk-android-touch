    def test_forty_developer_uncapped_override_wins(self):
        compiler = shlex.split(os.environ.get('CC', 'cc'))
        if not compiler or not shutil.which(compiler[0]):
            self.skipTest('A native C compiler is required')
        source = FRONTEND.read_text()
        parser = source[source.index('static const char *const settings_keys[] = {'):
                        source.index('static void env_default(')]
        with tempfile.TemporaryDirectory(prefix='totk-forty-parser-') as temp:
            directory = Path(temp)
            probe = directory / 'probe.c'
            probe.write_text('#define _GNU_SOURCE\n#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n' +
                             parser + '\nint main(int argc, char **argv) {\n'
                             'settings_file(argv[1]);\n'
                             'printf("menu=%s/%s\\n", getenv("TOTK_UNCAPPED"), getenv("TOTK_UNCAPPED_HZ"));\n'
                             'env_file(argv[2]);\n'
                             'printf("developer=%s/%s\\n", getenv("TOTK_UNCAPPED"), getenv("TOTK_UNCAPPED_HZ"));\n'
                             'return 0;\n}\n')
            binary = directory / 'probe'
            subprocess.run([*compiler, '-std=c11', str(probe), '-o', str(binary)], check=True, capture_output=True, text=True)
            settings, developer = directory / 'settings.env', directory / 'totk.env'
            settings.write_text(self.run_probe('env en-GB frame_rate=40')[0].replace('|', '\n'))
            for override, expected in (('TOTK_UNCAPPED=0\n', '0/40'),
                                       ('TOTK_UNCAPPED=1\nTOTK_UNCAPPED_HZ=55\n', '1/55')):
                developer.write_text(override)
                result = subprocess.run([str(binary), str(settings), str(developer)], check=True, capture_output=True, text=True)
                self.assertEqual(result.stdout.splitlines(), ['menu=1/40', 'developer=' + expected])
                self.assertNotIn('ignored', result.stderr)

    def test_gpu_feed_env_on_off_and_frame_generation(self):
        for rate in ('30', '40', '60', 'unlimited'):
            with self.subTest(frame_rate=rate):
                off = self.env(frame_rate=rate, gpu_feed='off')
                on = self.env(frame_rate=rate, gpu_feed='on')
                self.assertEqual([line for line in on if line not in GPU_FEED], off)
                self.assertEqual([line for line in on if line in GPU_FEED], GPU_FEED)
                self.assertFalse(any(line.startswith(('TOTK_VK_SPLIT_PASS_DRAWS', 'TOTK_ADPF_GPU')) for line in off))
        # Extraction refuses split passes, so neither hint is useful with frame generation; keep that env minimal.
        self.assertEqual(self.env(frame_gen='on', gpu_feed='on'), self.env(frame_gen='on', gpu_feed='off'))
        self.assertEqual(self.env(gpu_feed='invalid'), self.env(gpu_feed='off'))

    def test_preset_env_bytes(self):
        for preset, before in LEGACY_PRESET_ENV.items():
            with self.subTest(preset=preset):
                actual = self.run_probe(f'envpreset {preset} en-GB')[0].replace('|', '\n')
                self.assertEqual(actual, before)
                for soc in ('QCS8550', 'QCM8550', 'SM8550', 'CQ7790S', 'CQ7790M', 'SM7750', 'unknown', 'SM8650', 'XSM8750', 'CQ8725SA'):
                    self.assertEqual(self.run_probe(f'envsocpreset {preset} {soc} en-GB')[0].replace('|', '\n'), before)
                for feed in ('off', 'on'):
                    values = self.values(self.run_probe(f'apply {preset} gpu_feed={feed}')[0])
                    self.assertEqual(values['gpu_feed'], feed)
                    stored = ' '.join(f'{k}={v}' for k, v in values.items())
                    self.assertEqual(self.run_probe('preset ' + stored), [preset])
        duo = self.values(self.run_probe('applysoc 60fps CQ7790S')[0])
        self.assertEqual((duo['frame_rate'], duo['gpu_feed']), ('60', 'off'))
        odin = self.values(self.run_probe('applysoc light CQ8725S')[0])
        self.assertEqual((odin['frame_rate'], odin['gpu_feed']), ('30', 'on'))

    def test_hysteresis_is_only_the_odin_native_60fps_profile_policy(self):
        switch = 'TOTK_FPS60_HYSTERESIS=1\nTOTK_FRAME_LAG=1\n'
        for soc in ('CQ8725S', 'SM8750', 'cq8725s', 'SM8750-AB'):
            for preset, legacy in LEGACY_PRESET_ENV.items():
                with self.subTest(soc=soc, preset=preset):
                    # Before this change Odin added only the GPU feed pair, outside frame generation.
                    anchor = 'TOTK_GPU_TIME=hardware\n' if preset == '60fps' else 'TOTK_FPS60=0\n'
                    before = legacy if preset == 'smooth' else legacy.replace(anchor, anchor + '\n'.join(GPU_FEED) + '\n')
                    expected = before.replace('TOTK_GPU_TIME=hardware\n', 'TOTK_GPU_TIME=hardware\n' + switch)
                    actual = self.run_probe(f'envsocpreset {preset} {soc} en-GB')[0].replace('|', '\n')
                    self.assertEqual(actual.encode(), expected.encode())
                    if preset != '60fps':
                        self.assertEqual(actual.encode(), before.encode())
            # Internal policy is independent of the visible GPU feed choice and applies to custom 60 fps mixes.
            for line in switch.splitlines():
                self.assertIn(line, self.env(soc=soc, frame_rate='60', gpu_feed='off', shadows='low'))
                self.assertNotIn(line, self.env(soc=soc, frame_rate='30'))
                self.assertNotIn(line, self.env(soc=soc, frame_rate='60', frame_gen='on'))
            generated = self.run_probe(f'envsocpreset 60fps {soc} en-GB frame_gen=on')[0]
            self.assertNotIn('TOTK_FPS60_HYSTERESIS', generated)
            # Existing stores, including pre-gpu_feed preferences, gain the policy without adding a preference key.
            old = self.values(self.run_probe('apply 60fps overlay=full')[0])
            old.pop('gpu_feed')
            self.assertTrue(all(line in self.env(soc=soc, **old) for line in switch.splitlines()))
            old['gpu_feed'] = 'off'
            self.assertTrue(all(line in self.env(soc=soc, **old) for line in switch.splitlines()))
            self.assertNotIn('fps60_hysteresis', self.values(self.run_probe(f'storedsoc {soc} frame_rate=60')[0]))

    def test_frame_lag_only_adds_one_line_to_odin_native_sixty_bytes(self):
        for soc in ('CQ8725S', 'SM8750', 'cq8725s', 'SM8750-AB', 'QCS8550', 'QCM8550', 'SM8550',
                    'CQ7790S', 'CQ7790M', 'SM7750', 'unknown', 'SM8650', 'XSM8750', 'CQ8725SA'):
            elite = soc in ('CQ8725S', 'SM8750', 'cq8725s', 'SM8750-AB')
            for rate in ('30', '40', '60', 'unlimited'):
                for framegen in ('off', 'on'):
                    for feed in ('off', 'on'):
                        with self.subTest(soc=soc, rate=rate, framegen=framegen, feed=feed):
                            # Freeze main's exact bytes for every supported rate and frame-generation state.
                            native60 = rate == '60' and framegen == 'off'
                            if framegen == 'on':
                                before = ENV_HEADER + '\n'.join(FRAMEGEN) + '\n' + ENV_TAIL
                            elif rate in ('40', 'unlimited'):
                                hints = GPU_FEED if feed == 'on' else []
                                timing = FORTY if rate == '40' else UNLIMITED
                                before = ENV_HEADER + '\n'.join(timing + hints) + '\n' + ENV_TAIL
                            else:
                                head = ['TOTK_FPS60=1', 'TOTK_GPU_TIME=hardware'] if native60 else ['TOTK_FPS60=0']
                                if native60 and elite:
                                    head += ['TOTK_FPS60_HYSTERESIS=1']
                                if feed == 'on':
                                    head += GPU_FEED
                                before = ENV_HEADER + '\n'.join(head) + '\nTOTK_ACQUIRE_SLACK=1\n' + ENV_TAIL
                            expected = before
                            if native60 and elite:
                                expected = before.replace('TOTK_FPS60_HYSTERESIS=1\n',
                                                          'TOTK_FPS60_HYSTERESIS=1\nTOTK_FRAME_LAG=1\n')
                            actual = self.run_probe(f'envsoc {soc} en-GB frame_rate={rate} frame_gen={framegen} gpu_feed={feed}')[0].replace('|', '\n')
                            self.assertEqual(actual.encode(), expected.encode())
            first = self.run_probe(f'envfirst {soc} en-GB')[0].replace('|', '\n')
            preset = '60fps' if elite else 'balanced' if soc in ('QCS8550', 'QCM8550', 'SM8550') else 'light'
            self.assertEqual(first, self.run_probe(f'envsocpreset {preset} {soc} en-GB')[0].replace('|', '\n'))
            self.assertEqual('TOTK_FRAME_LAG=1\n' in first, elite)

