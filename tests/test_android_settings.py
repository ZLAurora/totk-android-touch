    def test_env_write_is_atomic_and_reports_failures(self):
        # The menu refuses to start the game silently when this write fails (Retry / Start anyway), so failures must
        # surface as an exception with a reason and must never leave a partial file or a stray temp file behind.
        with tempfile.TemporaryDirectory() as temp:
            d = Path(temp)
            self.assertEqual(self.run_probe(f'write {d} settings.env A=1'), ['ok'])
            self.assertEqual((d / 'settings.env').read_text(), 'A=1')
            self.assertEqual(sorted(p.name for p in d.iterdir()), ['settings.env'])
            self.assertEqual(self.run_probe(f'write {d} settings.env B=2'), ['ok'])
            self.assertEqual((d / 'settings.env').read_text(), 'B=2')
            # temp file cannot be created (a directory is in its place): the old file stays as it was
            (d / 'settings.env.tmp').mkdir()
            answer = self.run_probe(f'write {d} settings.env C=3')[0]
            self.assertTrue(answer.startswith('error '), answer)
            self.assertEqual((d / 'settings.env').read_text(), 'B=2')
            self.assertFalse((d / 'settings.env.tmp').exists())   # the failed temp path is cleaned up too
            # rename fails (the target is a non-empty directory): the temp file is removed again
            (d / 'blocked').mkdir(); (d / 'blocked' / 'x').write_text('x')
            answer = self.run_probe(f'write {d} blocked C=3')[0]
            self.assertTrue(answer.startswith('error '), answer)
            self.assertFalse((d / 'blocked.tmp').exists())
            # the folder itself is missing
            answer = self.run_probe(f'write {d / "missing"} settings.env C=3')[0]
            self.assertTrue(answer.startswith('error '), answer)
            self.assertFalse((d / 'missing').exists())

