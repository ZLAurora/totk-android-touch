class SettingsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        javac, java = shutil.which('javac'), shutil.which('java')
        if not javac or not java:
            raise unittest.SkipTest('javac/java not found')
        cls.java = java
        cls.temp = tempfile.TemporaryDirectory(prefix='totk-settings-')
        cls.classes = Path(cls.temp.name)
        subprocess.run([javac, '--release', '17', '-encoding', 'UTF-8', '-d', str(cls.classes), str(SOURCE), str(PROBE)],
                       check=True, capture_output=True, text=True)

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def run_probe(self, *commands):
        result = subprocess.run([self.java, '-cp', str(self.classes), 'com.aure.totk.setup.SettingsProbe'],
                                input='\n'.join(commands) + '\n', capture_output=True, text=True, timeout=60, check=True)
        return result.stdout.splitlines()

    def values(self, line):
        return dict(pair.split('=', 1) for pair in line.split())

    def env(self, locale='en-GB', soc=None, **stored):
        command = 'env ' if soc is None else f'envsoc {soc} '
        line = self.run_probe(command + locale + ''.join(f' {k}={v}' for k, v in stored.items()))[0]
        lines = line.split('|')[:-1]
        self.assertTrue(lines[0].startswith('# Generated by the TotK Native menu'), lines[0])
        body = [l for l in lines if not l.startswith('#')]
        keys = [l.split('=', 1)[0] for l in body]
        self.assertLessEqual(set(keys), ALLOWED)
        self.assertEqual(len(keys), len(set(keys)), 'a key written twice')
        return body

    def test_allowlist_matches_the_runtime(self):
        import re
        source = FRONTEND.read_text()
        block = source[source.index('settings_keys[] = {'):]
        block = block[:block.index('};')]
        self.assertEqual(set(re.findall(r'"([A-Z0-9_]+)"', block)), ALLOWED)

    def test_default_env_is_the_shipping_behaviour(self):
        self.assertEqual(self.env(), [
            'TOTK_FPS60=0', 'TOTK_ACQUIRE_SLACK=1', 'TOTK_POST_SCALE=off', 'TOTK_OPERATION_MODE=handheld', 'TOTK_NATIVE_UI=0',
            'TOTK_OVERLAY=off', 'TOTK_OVERLAY_POS=tr', 'TOTK_COMPANION=1', 'TOTK_FACE_BUTTONS=label', 'TOTK_AUDIO_PREFILL_MS=20',
            'TOTK_RUMBLE=1', 'TOTK_RUMBLE_GAIN=1.0', 'TOTK_GYRO=1', 'TOTK_LOCALE=en-GB'])

    def test_every_option_maps_as_the_contract_says(self):
        env = self.env('-', frame_rate='60', render_res='960x540', latency='smoothest', upscaler='fsr', sharpness_fsr='35',
                       aa='smaa', shadows='low', console_mode='docked', native_hud='on', overlay='full', overlay_pos='bl',
                       second_screen='off', buttons='xbox', audio_latency='safe', rumble='50', motion='off', game_language='pt-BR')
        self.assertEqual(env, [
            'TOTK_FPS60=1', 'TOTK_GPU_TIME=hardware', 'TOTK_RENDER_RES=960x540', 'TOTK_ACQUIRE_SLACK=2', 'TOTK_POST_SCALE=fsr', 'TOTK_POST_SHARPNESS=0.35',
            'TOTK_FXAA=0', 'TOTK_POST_AA=smaa', 'TOTK_SHADOW_RES=256', 'TOTK_OPERATION_MODE=docked', 'TOTK_NATIVE_UI=1',
            'TOTK_OVERLAY=full', 'TOTK_OVERLAY_POS=bl', 'TOTK_COMPANION=0', 'TOTK_FACE_BUTTONS=position',
            'TOTK_AUDIO_PREFILL_MS=40', 'TOTK_RUMBLE=1', 'TOTK_RUMBLE_GAIN=0.5', 'TOTK_GYRO=0', 'TOTK_LANG=pt-BR'])
        self.assertIn('TOTK_ACQUIRE_SLACK=0', self.env(latency='responsive'))
        self.assertFalse(any(l.startswith('TOTK_GPU_TIME') for l in self.env(frame_rate='30')))   # 30 fps: the runtime's default
        self.assertIn('TOTK_SHADOW_RES=288', self.env(shadows='medium'))
